"""Which project files the memory keeper may read, and which changed since its last run; every file is opened read-only (T1599-M09)."""
import hashlib
import os
import re
import sys

import memory_store
from agent_work import agent_work

SUMS = "archive/2026-11-auto-memory/SHA256SUMS"
GENERATED = "<!-- generated by"
FOLDER_FILES = ("CLAUDE.md", "CLAUDE.local.md", os.path.join(".claude", "CLAUDE.md"))


def enc(path):
    """Claude Code's per-project folder name for a path: every character outside [A-Za-z0-9] becomes '-'."""
    return re.sub(r"[^A-Za-z0-9]", "-", path)


def projects_dir():
    return os.path.join(os.environ.get("CLAUDE_CONFIG_DIR") or os.path.expanduser("~/.claude"), "projects")


def state_file():
    """The sha256 list of the last marked run: outside the store."""
    return os.path.join(agent_work(), "memory-keeper", "sources.tsv")


def tilde(path):
    h = os.path.expanduser("~")
    return "~" + path[len(h):] if path.startswith(h + "/") else path


def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def _md(folder):
    """The *.md regular files directly in folder (no walk), sorted."""
    try:
        names = sorted(os.listdir(folder))
    except OSError:
        return []
    return [p for p in (os.path.join(folder, n) for n in names if n.endswith(".md")) if os.path.isfile(p) and not os.path.islink(p)]


def _protected_roots():
    """Protected repo and path entries; None when the matcher fails (then every source counts as protected)."""
    try:
        import protectedlib
        return [os.path.normpath(p) for p in protectedlib.lexical_paths()]
    except Exception as e:  # fail closed
        print(f"memory sources: protected matcher failed ({e}); every source flagged protected", file=sys.stderr)
        return None


def candidates(store):
    """[(domain, path, protected)] of every file the keeper may read, before the --changed filter."""
    roots = _protected_roots()
    rows = []
    for w, d, fl in store.map():
        if w.startswith("seat:"):
            continue
        f = os.path.normpath(os.path.expanduser(w))
        prot = roots is None or "protected" in fl or any(f == r or f.startswith(r + "/") for r in roots)
        rows.append((f, d, prot))
    out = []
    for f, d, prot in rows:
        out += [(d, os.path.join(f, n), prot) for n in FOLDER_FILES]
        out += [(d, p, prot) for p in _md(os.path.join(f, ".claude", "rules"))]

    pd, home_key = projects_dir(), enc(os.path.expanduser("~"))
    keys = sorted(((enc(f), d, prot) for f, d, prot in rows), key=lambda r: -len(r[0]))
    for s in sorted(os.listdir(pd)) if os.path.isdir(pd) else []:
        hit = next((r for r in keys if s == r[0] or s.startswith(r[0] + "-")), None)
        if s != home_key and hit:
            out += [(hit[1], p, hit[2]) for p in _md(os.path.join(pd, s, "memory"))]

    owner = next((d for w, d, fl in store.map() if w.startswith("seat:") and "owner" in fl), "orchestrator")
    done = {}
    if os.path.isfile(store.path(SUMS)):
        with open(store.path(SUMS), encoding="utf-8") as f:
            done = {os.path.basename(l.split(None, 1)[1].strip()): l.split()[0] for l in f if len(l.split()) >= 2}
    for p in _md(os.path.join(pd, home_key, "memory")):
        with open(p, encoding="utf-8", errors="replace") as f:
            if f.readline().startswith(GENERATED):
                continue
        if done.get(os.path.basename(p)) != sha(p):
            out.append((owner, p, False))

    prot_domains = {d for _, d, fl in store.map() if "protected" in fl}
    out += [(os.path.basename(p)[:-3], p, roots is None or os.path.basename(p)[:-3] in prot_domains)
            for p in _md(os.path.join(agent_work(), "decisions")) if os.path.basename(p)[:-3] in store.domains()]
    seen = set()
    return [r for r in out if os.path.isfile(r[1]) and not os.path.islink(r[1]) and not (r[1] in seen or seen.add(r[1]))]


def _state():
    try:
        with open(state_file(), encoding="utf-8") as f:
            return dict(l.rstrip("\n").split("\t", 1) for l in f if "\t" in l)
    except FileNotFoundError:
        return {}


def sources(store, changed=False, mark=False):
    """[(domain, path, protected)]; changed: only files new or different since the last mark; mark: remember every sha now."""
    rows = [(d, p, prot, sha(p)) for d, p, prot in candidates(store)]
    old = _state() if changed else {}
    out = [(d, p, prot) for d, p, prot, h in rows if not changed or old.get(tilde(p)) != h]
    if mark:
        memory_store._atomic(state_file(), "".join(f"{tilde(p)}\t{h}\n" for _, p, _, h in rows))
    return out
