"""The keeper's transaction as code: a staging copy, the gate, move in, notes filed, views rebuilt, commit, guarded push (T1599-M09)."""
import hashlib
import os
import shutil
import subprocess
import tempfile
import time

import memory_check
import memory_store
from agent_work import agent_work

NOTES = "archive/notes"
LEDGER = "core/ledger.md"


def _base(staging):
    return staging.rstrip("/") + ".base.tsv"


def files(root):
    """{relative path: sha256} of every file under root, .git left out."""
    out = {}
    for r, ds, fs in os.walk(root):
        ds[:] = [d for d in ds if d != ".git"]
        for n in fs:
            p = os.path.join(r, n)
            if os.path.isfile(p):
                with open(p, "rb") as f:
                    out[os.path.relpath(p, root)] = hashlib.sha256(f.read()).hexdigest()
    return out


def git(store, *args, check=True, input=None):
    r = subprocess.run(["git", "-C", store.root, *args], capture_output=True, text=True, input=input)
    if check and r.returncode:
        raise RuntimeError(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r


def stage(store):
    """Copy the store (no .git) to a new staging folder beside the keeper's papers; the store itself is not touched."""
    top = os.path.join(agent_work(), "memory-keeper")
    os.makedirs(top, exist_ok=True)
    path = tempfile.mkdtemp(prefix="staging-", dir=top)
    shutil.copytree(store.root, path, symlinks=True, dirs_exist_ok=True, ignore=shutil.ignore_patterns(".git"))
    memory_store._atomic(_base(path), "".join(f"{k}\t{v}\n" for k, v in sorted(files(store.root).items())))
    return path


def is_note(rel):
    return rel.startswith("inbox/") and rel.count("/") == 1 and rel != "inbox/.gitkeep"


def _put(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(dst), prefix=".tmp-")
    os.close(fd)
    shutil.copy2(src, tmp)
    os.replace(tmp, dst)


def _read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def commit_others(store, today):
    """Commit edits made outside the keeper first: a manager's domain as `<manager>:`, the rest as `owner:` plus a ledger line."""
    st = git(store, "status", "--porcelain", "-z", "--untracked-files=all").stdout
    paths = [e[3:] for e in st.split("\0") if len(e) > 3 and "inbox" not in e[3:].split("/")]
    groups = {}
    for p in paths:
        parts, who = p.split("/"), "owner"
        if parts[0] == "domains" and len(parts) > 2 and os.path.isfile(store.path(f"domains/{parts[1]}/OWNER")):
            w = _read(store.path(f"domains/{parts[1]}/OWNER")).strip()
            who = w if w and w != "keeper" else "owner"
        groups.setdefault(who, []).append(p)
    for who, ps in sorted(groups.items()):
        if who == "owner" and os.path.isfile(store.path(LEDGER)):
            with open(store.path(LEDGER), "a", encoding="utf-8") as f:
                f.write(f"- {today} · owner edit, committed before the keeper run: {', '.join(sorted(ps))} · (git `owner:` commit)\n")
            ps = sorted(set(ps) | {LEDGER})
        git(store, "add", "-A", "--", *ps)
        git(store, "commit", "-q", "-m", f"{who}: edits before the keeper run {today}")
        print(f"apply · committed {len(ps)} file(s) as {who}:")


def index(store):
    """INDEX.md: one line per card and topic file: path, bytes, newest owner date, its first heading (none for PRIVATE)."""
    rows = []
    for p in store.pages():
        if p.endswith("/ledger.md"):
            continue
        text = store.text(p)
        dates = sorted(d for l in store.lines(p) for d in l.dates)
        head = next((l.lstrip("#").split(":")[0].strip() for l in text.splitlines() if l.startswith("#")), "")
        words = "" if store.private_seats(p) is not None else head[:30]
        rows.append(f"- {p} {len(text.encode('utf-8'))} {dates[-1] if dates else '-'} {words}".rstrip())
    return ("# Index (generated by `memory apply`; per page: path, bytes, newest owner date, heading)\n"
            + "\n".join(rows) + "\n")


def orchestrator_page(store, car):
    """Rewrite the orchestrator's MEMORY.md from the store, only once `memory install` made it a generated page."""
    path = os.path.join(car.project_dir(car.git_root(car.home())), "memory", "MEMORY.md")
    old, page = car.read(path), car.generated(store)
    if not old or not old.startswith(car.MARK):
        return "memory-md · skipped · not a generated page yet (memory install)"
    if not page or page == old:
        return "memory-md · unchanged"
    if page.count("\n") > car.MEMORY_LINES or len(page.encode("utf-8")) > car.MEMORY_BYTES:
        return f"memory-md · skipped · over {car.MEMORY_LINES} lines or {car.MEMORY_BYTES} B"
    memory_store._atomic(path, page)
    return "memory-md · regenerated"


def push(store):
    """Push only to an origin whose GitHub visibility reads back PRIVATE; one line either way."""
    if git(store, "remote", "get-url", "origin", check=False).returncode:
        return "push · skipped · no origin"
    try:
        vis = subprocess.run(["gh", "repo", "view", "--json", "visibility", "-q", ".visibility"], cwd=store.root,
                             capture_output=True, text=True, timeout=60).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        vis = ""
    if vis != "PRIVATE":
        return f"push · skipped · visibility reads {vis or 'nothing'}, not PRIVATE"
    r = git(store, "push", "-q", "origin", "HEAD", check=False)
    return "push · ok" if r.returncode == 0 else f"push · failed · exit {r.returncode}"


def apply(store, staging, car=None):
    """Gate the staging copy and move it in; exit code 0 green, 1 red (nothing of the staging moved), 2 not a staging folder."""
    staging = os.path.abspath(staging)
    if not os.path.isfile(_base(staging)) or staging == store.root or staging.startswith(store.root + "/"):
        print(f"memory apply: {staging} is not a staging folder made by `memory stage`")
        return 2
    base = dict(l.rstrip("\n").split("\t", 1) for l in open(_base(staging), encoding="utf-8") if "\t" in l)
    stg, today = memory_store.Store(staging), time.strftime("%Y-%m-%d")
    commit_others(store, today)

    notes = sorted(r for r in base if is_note(r))
    bad = {f.file: f.checker for f in memory_check.secrets(store, {}) + memory_check.machine_values(store, {})}
    rejected = {r: bad[r] for r in notes if r in bad}
    for r in notes:
        src = store.path(r) if os.path.isfile(store.path(r)) else stg.path(r)
        if r not in rejected and os.path.isfile(src):
            _put(src, stg.path(f"{NOTES}/{os.path.basename(r)}"))
        if os.path.isfile(stg.path(r)):
            os.remove(stg.path(r))

    now, new, red = files(store.root), files(staging), []
    for rel in sorted(set(base) | set(now) | set(new)):
        b, n, s = base.get(rel), now.get(rel), new.get(rel)
        if s == n or (s is None and is_note(rel)):
            continue
        if s == b:  # only the store changed since `memory stage` (his edit): carry it into the staging copy
            if n is None:
                os.remove(stg.path(rel))
            else:
                _put(store.path(rel), stg.path(rel))
        elif n == b and s is None:
            red.append(f"apply · red · {rel} · the staging copy removes a file: retire lines, never delete a page")
        elif n != b and not (None not in (b, n, s) and rel.endswith("ledger.md") and _append_merge(store, stg, rel, b)):
            red.append(f"apply · red · {rel} · changed in the store and in the staging copy since `memory stage`")
    if red:
        print("\n".join(red))
        return 1

    if os.path.isdir(stg.path("checks/ids.d")):
        import memory_quiz
        memory_quiz.merge(stg)
    memory_store._atomic(stg.path("INDEX.md"), index(stg))
    armed = os.path.isfile(store.path("checks/quiz-baseline.tsv"))
    found = memory_check.run(stg, memory_check.before_dir(store.root), also=["quiz-changed"] if armed else [])
    if found:
        print("\n".join("apply · red · " + memory_check.fmt(f) for f in found))
        print("apply · red · nothing moved; the notes stay in the inbox")
        return 1

    new = files(staging)
    take = sorted({r for r in new if new[r] != now.get(r)} | {r for r in notes if r in now})
    rej_dir = os.path.join(agent_work(), "memory-keeper", "rejected")
    for r in take:
        if r in new:
            _put(stg.path(r), store.path(r))
        else:
            if r in rejected:
                os.makedirs(rej_dir, mode=0o700, exist_ok=True)
                shutil.copy2(store.path(r), os.path.join(rej_dir, os.path.basename(r)))
            os.remove(store.path(r))
    for r, checker in sorted(rejected.items()):
        print(f"apply · rejected · {r} · {checker} (kept outside the store)")
    ignored = set(git(store, "check-ignore", "--stdin", check=False, input="\n".join(take)).stdout.split("\n"))
    tracked = set(git(store, "ls-files").stdout.splitlines())
    for r in take:
        if r in new and r not in ignored:
            git(store, "add", "--", r)
        elif r not in new and r in tracked:
            git(store, "rm", "-q", "--cached", "--", r)
    filed = len(notes) - len(rejected)
    if git(store, "diff", "--cached", "--quiet", check=False).returncode:
        git(store, "commit", "-q", "-m", f"keeper: {today}, {len(take)} file(s), {filed} note(s) filed, {len(rejected)} rejected")
    if car is not None:
        print(orchestrator_page(store, car))
    print(push(store))
    shutil.rmtree(staging)
    os.remove(_base(staging))
    print(f"apply · green · {len(take)} file(s) moved in, {filed} note(s) filed, {len(rejected)} rejected")
    return 0


def _append_merge(store, stg, rel, base_sha):
    """An append-only ledger changed on both sides: the store's text plus the staging copy's new tail, when both extend the base."""
    live, mine = _read(store.path(rel)), _read(stg.path(rel))
    a, b = live.splitlines(keepends=True), mine.splitlines(keepends=True)
    k = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
    head = "".join(a[:k])
    if hashlib.sha256(head.encode("utf-8")).hexdigest() != base_sha:
        return False
    memory_store._atomic(stg.path(rel), live + "".join(b[k:]))
    return True
